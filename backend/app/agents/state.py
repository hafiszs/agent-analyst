from __future__ import annotations

from typing import Any, TypedDict
from ..jobs import Job
from .base import StepResult


class AgentState(TypedDict, total=False):
    """LangGraph shared agent workflow state.

    Attributes:
        job: The active analysis job containing files, metadata, and directories.
        profile: The parsed profile JSON digest from the profiler agent.
        plan: The execution plan and intent generated by the planner agent.
        clean_result: Execution result and code from the cleaner agent.
        eda_result: Execution result and findings from the EDA agent.
        report: Final synthesized report with verified citations.
        evidence: Evidence registry mapping ID (e.g., 'p0', 'c1', 'f1') to code & output.
        warnings: List of runtime warnings accumulated across steps.
        needs_reclean: Flag set by EDA agent if data quality anomaly triggers loop-back.
        reclean_count: Number of times clean-eda loop has been executed.
        error: Fatal error message if pipeline aborted early.
    """
    job: Job
    profile: dict | None
    plan: dict | None
    clean_result: StepResult | None
    eda_result: StepResult | None
    report: dict | None
    evidence: dict[str, Any]
    warnings: list[str]
    needs_reclean: bool
    reclean_count: int
    error: str | None
